// Extracts only the icons used in src/data/data.js from `tech-stack-icons`
// so the app doesn't ship the package's full 700+ icon set (~9 MB of JS).
// Run: npm run icons
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const all = require("tech-stack-icons/icons.json");
const data = readFileSync("src/data/data.js", "utf8");
const used = [...new Set([...data.matchAll(/icon: "([a-z0-9]+)"/g)].map((m) => m[1]))].sort();

const MAX = 60 * 1024;

// namespace ids so inline SVGs on one page don't clash (clip paths, gradients)
function namespaced(svg, prefix) {
  const ids = [...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) {
    svg = svg
      .replaceAll(`id="${id}"`, `id="${prefix}-${id}"`)
      .replaceAll(`url(#${id})`, `url(#${prefix}-${id})`)
      .replaceAll(`href="#${id}"`, `href="#${prefix}-${id}"`);
  }
  return svg;
}

const out = {};
for (const name of used) {
  const { dark, light } = all[name]?.svg ?? {};
  if (!dark && !light) throw new Error(`Icon not found in tech-stack-icons: ${name}`);
  const d = dark ?? light;
  const l = light ?? dark;
  if (d.length > MAX || l.length > MAX) {
    console.warn(`Skipping ${name}: too heavy (${Math.round(Math.max(d.length, l.length) / 1024)}KB). Give it an iconSrc fallback in data.js.`);
    continue;
  }
  // "dark" = shown on dark backgrounds, "light" = on light ones. Omit light if identical.
  out[name] = d === l ? { dark: namespaced(d, `${name}-d`) } : { dark: namespaced(d, `${name}-d`), light: namespaced(l, `${name}-l`) };
}

writeFileSync(
  "src/data/stackIcons.js",
  `// AUTO-GENERATED by scripts/extract-stack-icons.mjs from tech-stack-icons (dark + light variants).\n// Do not edit by hand. Re-run \`npm run icons\` after changing \`icon:\` names in data.js.\nexport const stackIcons = ${JSON.stringify(out, null, 2)};\n`
);
console.log(`Wrote ${used.length} icons: ${used.join(", ")}`);
